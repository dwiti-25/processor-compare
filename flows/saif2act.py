#!/usr/bin/env python3
"""Convert a Verilator SAIF (RTL sim, flows/sim.sh SAIF=1) into a clock-normalised activity list
for OpenSTA power analysis of the flattened layout netlist (flows/power.sh).

usage: flows/saif2act.py <in.saif> <out.tcl> [--scope tb_top/dut]

Output: a Tcl file defining
    set pwr_window_cycles <N>
    set pwr_acts { {<flat net name> <toggles per clock cycle> <duty>} ... }
Flat net name = hierarchy below the scope joined with '.', as Yosys names nets when it flattens
(e.g. u_core.core.xm_memop[0]); nets of the scope instance itself keep their plain names (ports).

Why per clock cycle: the testbench clock period is 10 time units with no meaning in ns, so absolute
densities from the SAIF would be wrong. Per-cycle activity is scaled to the layout's clock target in
power.tcl. The window length comes from the clock net's toggle count (TC/2): Verilator counts toggles
only after $dumpvars (the CoreMark start marker), while DURATION/T0/T1 run from time 0, so duty is
T1/DURATION (includes the ~4% of time before the window; affects leakage-state weighting only).
"""
import re
import sys

TOK = re.compile(r"\(|\)|[^\s()]+")


def tokens(path):
    with open(path) as f:
        for line in f:
            if line.lstrip().startswith("//"):
                continue
            yield from TOK.findall(line)


def unescape(name):
    return re.sub(r"\\(.)", r"\1", name)


def parse(path, scope):
    scope = scope.split("/")
    stack = []          # instance path
    duration = None
    acts = {}           # flat name -> (tc, t1)
    clk_tc = None
    it = tokens(path)
    depth_kind = []     # kind of each open paren: 'inst', 'net', 'entry', 'other'
    expect = None
    cur = None
    for t in it:
        if t == "(":
            expect = "kw"
            continue
        if t == ")":
            kind = depth_kind.pop() if depth_kind else None
            if kind == "inst":
                stack.pop()
            elif kind == "entry" and cur is not None:
                name, vals = cur
                if stack[: len(scope)] == scope:
                    rel = stack[len(scope):]
                    flat = ".".join(rel + [name])
                    acts[flat] = (vals.get("TC", 0), vals.get("T1", 0))
                    if not rel and name == "clk":
                        clk_tc = vals.get("TC", 0)
                cur = None
            elif kind == "val":
                pass
            continue
        if expect == "kw":
            expect = None
            if t == "INSTANCE":
                depth_kind.append("inst")
                stack.append(unescape(next(it)))
            elif t == "NET" or t == "PORT":
                depth_kind.append("net")
            elif t == "DURATION":
                depth_kind.append("val")
                duration = int(next(it))
            elif depth_kind and depth_kind[-1] == "net":
                depth_kind.append("entry")
                cur = (unescape(t), {})
            elif depth_kind and depth_kind[-1] == "entry":
                depth_kind.append("val")
                cur[1][t] = int(next(it))
            else:
                depth_kind.append("other")
    return duration, clk_tc, acts


def main():
    args = sys.argv[1:]
    scope = "tb_top/dut"
    if "--scope" in args:
        i = args.index("--scope")
        scope = args[i + 1]
        del args[i:i + 2]
    src, dst = args
    duration, clk_tc, acts = parse(src, scope)
    if not clk_tc or not duration:
        sys.exit(f"saif2act: no clk toggles or DURATION under scope {scope}")
    cycles = clk_tc / 2.0
    with open(dst, "w") as f:
        f.write(f"# generated by flows/saif2act.py from {src}\n")
        f.write(f"set pwr_window_cycles {cycles:.0f}\n")
        f.write("set pwr_acts {\n")
        for name, (tc, t1) in acts.items():
            if name in ("clk",):
                continue  # clock activity comes from the SDC clock
            f.write("{%s} %.6g %.4f\n" % (name, tc / cycles, t1 / duration))
        f.write("}\n")
    print(f"saif2act: {len(acts)} nets, window {cycles:.0f} cycles -> {dst}")


if __name__ == "__main__":
    main()
