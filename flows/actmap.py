#!/usr/bin/env python3
"""Map RTL switching activity (Verilator SAIF) onto the flattened layout netlist, register by register.

saif2act.py matches SAIF and netlist names literally. That is wrong or incomplete in three cases,
all seen in Ibex (DECISIONS.md, 2026-11-11):
  1. Vectors whose declared LSB is not 0 (e.g. logic [31:8] rdata_q): Verilator's SAIF renumbers bits
     from 0, the netlist keeps the RTL bit index. Literal matching silently pairs the wrong bits.
     Fix: shift by the declared LSB, taken from a 1-cycle VCD header (VCD keeps declared ranges).
  2. Unpacked arrays (logic [63:0] mhpmcounter [32]): SAIF names them base[e][i], the netlist (Yosys
     flatten of the slang frontend's packed array) uses one linear index. Fix: linear = (N-1-e)*W + i
     (element 0 in the top bits; checked on Ibex: minstret = element 2 -> bits 1856..1919, and the unused
     imd_val_q_i[1][33:32] are exactly the linear bits 32..33 missing from the netlist).
  3. FSM state registers re-encoded by Yosys (fsm_recode, e.g. binary -> one-hot): netlist bit k is not
     RTL bit k. Fix: per-state cycles and state-to-state transitions over the same window from a
     generated testbench monitor (--gen-mon), mapped through the encoding printed in the Yosys log.

usage:
  flows/actmap.py --gen-mon <yosys-synthesis.log> <out.svh>
  flows/actmap.py --saif S --vcdhdr V --yosys-log L --mon-log M --netlist N --out acts.tcl [--report R]
Output format is the same as saif2act.py (set pwr_window_cycles / set pwr_acts), with netlist names.
"""
import argparse
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from saif2act import parse as parse_saif  # noqa: E402

SCOPE_VCD = ["tb_top", "dut"]


def parse_recodes(log):
    """Yosys FSM_RECODE blocks -> {flat fsm name: [state code ints, by one-hot/bit position]}."""
    fsms, cur = {}, None
    for line in open(log):
        m = re.match(r"Recoding FSM `\$fsm\$\\(\S+?)\$\d+' from module .* using `(\S+)' encoding:", line)
        if m:
            cur = m.group(1)
            fsms[cur] = {"codes": [], "width": None, "enc": m.group(2)}
            continue
        if cur:
            m = re.match(r"\s+([01]+) -> ([-01]+)\s*$", line)
            if m:
                code, onehot = m.groups()
                # Yosys prints constants MSB first; position = index of the '1' from the right
                pos = len(onehot) - 1 - onehot.index("1")
                fsms[cur]["width"] = len(code)
                fsms[cur]["codes"].append((pos, int(code, 2)))
                fsms[cur]["nbits"] = len(onehot)
            elif "mapping" in line:
                fsms[cur]["mapping"] = line.strip()
            elif line.strip() == "" or not line.startswith(" "):
                cur = None
    for f in fsms.values():
        if "one-hot" not in f.get("mapping", "") and f["enc"] != "one-hot":
            sys.exit(f"actmap: FSM encoding other than one-hot not supported: {f}")
    return fsms


def gen_mon(log, out):
    fsms = parse_recodes(log)
    L = [f"// generated by flows/actmap.py --gen-mon from {log}",
         "// FSM state monitor over the dump window (tb_top saif_on); see actmap.py"]
    rep = ["task automatic pwr_mon_report();"]
    for i, (name, f) in enumerate(sorted(fsms.items())):
        w, n = f["width"], 1 << f["width"]
        sig = "dut." + name
        L += [f"// FSM {i}: {name} ({w} bits, {len(f['codes'])} states)",
              f"longint unsigned pm{i}_cyc [0:{n - 1}];",
              f"longint unsigned pm{i}_tr [0:{n - 1}][0:{n - 1}];",
              f"logic [{w - 1}:0] pm{i}_prev; bit pm{i}_have = 0;",
              "always @(posedge clk) if (saif_on) begin",
              f"  pm{i}_cyc[{sig}] = pm{i}_cyc[{sig}] + 1;",
              f"  if (pm{i}_have && {sig} != pm{i}_prev) pm{i}_tr[pm{i}_prev][{sig}] = pm{i}_tr[pm{i}_prev][{sig}] + 1;",
              f"  pm{i}_prev = {sig}; pm{i}_have = 1;",
              "end"]
        rep += [f"  for (int a = 0; a < {n}; a++) begin",
                f"    if (pm{i}_cyc[a] != 0) $display(\"PWRMON fsm={name} state=%0d cycles=%0d\", a, pm{i}_cyc[a]);",
                f"    for (int b = 0; b < {n}; b++) if (pm{i}_tr[a][b] != 0)",
                f"      $display(\"PWRMON fsm={name} from=%0d to=%0d count=%0d\", a, b, pm{i}_tr[a][b]);",
                "  end"]
    rep.append("endtask")
    with open(out, "w") as fo:
        fo.write("\n".join(L + rep) + "\n")
    print(f"actmap: monitor for {len(fsms)} FSMs -> {out}")


def parse_vcd_header(path):
    """-> ranges {flat base: (msb, lsb)}, arrays {flat base: (n_elems, msb, lsb)} below tb_top.dut."""
    st, ranges, arrays = [], {}, {}
    for line in open(path):
        f = line.split()
        if not f:
            continue
        if f[0] == "$scope":
            st.append(f[2])
        elif f[0] == "$upscope":
            st.pop()
        elif f[0] == "$var":
            if st[:2] != SCOPE_VCD:
                continue
            name = f[4]
            rng = f[5] if len(f) > 6 and f[5].startswith("[") else None
            msb, lsb = (map(int, rng[1:-1].split(":")) if rng else (0, 0))
            rel = ".".join(st[2:] + [name])
            m = re.match(r"^(.*)\[(\d+)\]$", rel)
            if m:  # array element (Verilator emits one var per element)
                base, e = m.group(1), int(m.group(2))
                n = max(arrays.get(base, (0,))[0], e + 1)
                arrays[base] = (n, msb, lsb)
            else:
                ranges[rel] = (msb, lsb)
        elif f[0] == "$enddefinitions":
            break
    return ranges, arrays


def parse_mon(path):
    cyc, tr = defaultdict(dict), defaultdict(dict)
    for line in open(path):
        m = re.match(r"PWRMON fsm=(\S+) state=(\d+) cycles=(\d+)", line)
        if m:
            cyc[m.group(1)][int(m.group(2))] = int(m.group(3))
        m = re.match(r"PWRMON fsm=(\S+) from=(\d+) to=(\d+) count=(\d+)", line)
        if m:
            tr[m.group(1)][(int(m.group(2)), int(m.group(3)))] = int(m.group(4))
    return cyc, tr


def netlist_regs(path):
    """-> (all net names, {register Q net: instance})"""
    txt = open(path).read()
    nets = set(n.strip() for n in re.findall(r"^\s*wire\s+(?:\[[^\]]*\]\s*)?\\?(\S+)\s*;", txt, re.M))
    regs = {}
    for m in re.finditer(r"sky130_fd_sc_hd__(\w+?)_\d+\s+(\S+)\s*\((.*?)\);", txt, re.S):
        typ, inst, body = m.groups()
        if not re.match(r"(df|edf|sdf|dl[rx])", typ):
            continue
        q = re.search(r"\.Q\(\\?([^\s)]+)\s*\)", body) or re.search(r"\.Q_N\(\\?([^\s)]+)\s*\)", body)
        if q:
            regs[q.group(1)] = inst
    # vector nets declared as  wire [31:0] name;  -> name[i]
    for m in re.finditer(r"^\s*wire\s+\[(\d+):(\d+)\]\s+\\?(\S+)\s*;", txt, re.M):
        hi, lo, n = int(m.group(1)), int(m.group(2)), m.group(3)
        for i in range(min(hi, lo), max(hi, lo) + 1):
            nets.add(f"{n}[{i}]")
    nets |= set(regs)
    return nets, regs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen-mon", nargs=2, metavar=("YOSYS_LOG", "OUT_SVH"))
    ap.add_argument("--saif"); ap.add_argument("--vcdhdr"); ap.add_argument("--yosys-log")
    ap.add_argument("--mon-log"); ap.add_argument("--netlist"); ap.add_argument("--out")
    ap.add_argument("--report")
    a = ap.parse_args()
    if a.gen_mon:
        return gen_mon(*a.gen_mon)

    duration, clk_tc, saif = parse_saif(a.saif, "/".join(SCOPE_VCD))
    cycles = clk_tc / 2.0
    ranges, arrays = parse_vcd_header(a.vcdhdr)
    fsms = parse_recodes(a.yosys_log)
    cyc, tr = parse_mon(a.mon_log)
    nets, regs = netlist_regs(a.netlist)

    acts = {}      # netlist name -> (act per cycle, duty, source description)
    naive = {}     # literal SAIF name -> act (what saif2act.py did)
    kinds = defaultdict(int)
    for name, (tc, t1) in saif.items():
        if name == "clk":
            continue
        act, duty = tc / cycles, t1 / duration
        naive[name] = act
        m2 = re.match(r"^(.*)\[(\d+)\]\[(\d+)\]$", name)
        m1 = re.match(r"^(.*)\[(\d+)\]$", name)
        if m2 and m2.group(1) in arrays:
            base, e, i = m2.group(1), int(m2.group(2)), int(m2.group(3))
            n, msb, lsb = arrays[base]
            w = abs(msb - lsb) + 1
            nl = f"{base}[{(n - 1 - e) * w + i}]"
            kind = "array"
        elif m1 and m1.group(1) in ranges:
            base, i = m1.group(1), int(m1.group(2))
            msb, lsb = ranges[base]
            if msb < lsb:
                sys.exit(f"actmap: ascending range not handled: {base} [{msb}:{lsb}]")
            nl = f"{base}[{lsb + i}]"
            kind = "lsb-shift" if lsb else "literal"
        else:
            nl, kind = name, "literal"
        base_of = re.sub(r"\[\d+\]$", "", nl)
        if base_of in fsms:
            continue  # RTL (binary) state bits do not exist in the re-encoded netlist
        acts[nl] = (act, duty, f"{kind}: SAIF {name}")
        kinds[kind] += 1

    fsm_lines = []
    for fname, f in fsms.items():
        total = sum(cyc[fname].values())
        if total == 0:
            sys.exit(f"actmap: no monitor data for FSM {fname} (rerun sim with PWRMON)")
        for pos, code in f["codes"]:
            t = sum(c for (x, y), c in tr[fname].items() if code in (x, y))
            nl = f"{fname}[{pos}]"
            acts[nl] = (t / total, cyc[fname].get(code, 0) / total,
                        f"fsm: one-hot bit {pos} = RTL state {code} ({f['width']}-bit), "
                        f"{cyc[fname].get(code, 0)} cycles, {t} toggles")
            fsm_lines.append((fname, pos, code, cyc[fname].get(code, 0), t, nl in regs))

    # report
    reg_names = sorted(regs)
    old = {r for r in reg_names if r in naive}
    new = {r for r in reg_names if r in acts}
    fixed_unmatched = sorted(set(reg_names) - old & new)
    still = sorted(set(reg_names) - new)
    wrong = sorted(r for r in old & new if not acts[r][2].startswith("literal"))
    R = [f"registers in netlist: {len(reg_names)}",
         f"matched literally before (saif2act.py): {len(old)}",
         f"matched now: {len(new)}",
         f"previously unmatched, now mapped: {len(fixed_unmatched)}",
         f"previously matched to the WRONG RTL bit, now corrected: {len(wrong)}",
         f"still unmatched: {len(still)}",
         f"SAIF nets by rule: " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())),
         "", "## previously unmatched -> RTL source"]
    R += [f"{r}  <-  {acts[r][2]}  (act/cycle {acts[r][0]:.4g}, duty {acts[r][1]:.3f})" for r in fixed_unmatched]
    R += ["", "## previously matched to the wrong RTL bit -> corrected source"]
    R += [f"{r}  <-  {acts[r][2]}  (was literal SAIF {r}: act/cycle {naive[r]:.4g}; now {acts[r][0]:.4g})"
          for r in wrong]
    R += ["", "## FSM one-hot bits (fsm, bit, RTL state, cycles in state, toggles, is a netlist register)"]
    R += [f"{a} [{b}] state={c} cycles={d} toggles={e} reg={g}" for a, b, c, d, e, g in fsm_lines]
    R += ["", "## still unmatched (default activity)"] + [f"{r} ({regs[r]})" for r in still]
    text = "\n".join(R) + "\n"
    if a.report:
        open(a.report, "w").write(text)
    print(text)

    with open(a.out, "w") as f:
        f.write(f"# generated by flows/actmap.py from {a.saif}\n")
        f.write(f"set pwr_window_cycles {cycles:.0f}\n")
        f.write("set pwr_acts {\n")
        for n, (act, duty, _) in acts.items():
            f.write("{%s} %.6g %.4f\n" % (n, act, duty))
        f.write("}\n")


if __name__ == "__main__":
    main()
