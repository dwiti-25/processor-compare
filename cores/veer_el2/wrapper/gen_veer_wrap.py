#!/usr/bin/env python3
"""Generate veer_el2_wrap.sv: el2_veer in the common wrapper interface.

el2_veer has ~200 ports (AXI/AHB variants, DMA slave, debug system bus, DCCM/ICCM/I-cache SRAM
ports, MPC/halt controls, trace). This script reads its port list from the vendor RTL and ties
every input not listed in CONNECT to zero, leaving unlisted outputs open, so nothing is missed.
usage: cores/veer_el2/wrapper/gen_veer_wrap.py > cores/veer_el2/wrapper/veer_el2_wrap.sv
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "rtl", "design", "el2_veer.sv")

# explicit connections (port -> expression); everything else: inputs '0, outputs open
CONNECT = {
    "clk": "clk",
    "rst_l": "rst_n",
    "dbg_rst_l": "rst_n",
    "rst_vec": "31'h0000_0040",          # reset vector 0x80 ([31:1])
    "nmi_vec": "31'h0000_0040",
    "core_id": "28'h0",
    "lsu_bus_clk_en": "1'b1",
    "ifu_bus_clk_en": "1'b1",
    "dbg_bus_clk_en": "1'b1",
    "dma_bus_clk_en": "1'b1",
    "timer_int": "irq_timer",
    "soft_int": "irq_soft",
    "extintsrc_req": "irq_ext",
    "scan_mode": "1'b0",
    # system bus (debug master) and DMA slave: idle, always ready
    "sb_axi_awready": "1'b1", "sb_axi_wready": "1'b1", "sb_axi_arready": "1'b1",
    "dma_axi_bready": "1'b1", "dma_axi_rready": "1'b1",
}
for ch in ("lsu", "ifu"):
    for sig in ("awvalid awready awid awaddr awlen wvalid wready wdata wstrb wlast bvalid bready bid "
                "bresp arvalid arready arid araddr arlen rvalid rready rid rdata rresp rlast").split():
        CONNECT[f"{ch}_axi_{sig}"] = f"{ch}_axi_{sig}"

hdr = open(SRC).read()
hdr = hdr[hdr.index("module el2_veer\n"):]
hdr = hdr[:hdr.index(");")]
hdr = re.sub(r"//.*", "", hdr)
hdr = re.sub(r"/\*.*?\*/", "", hdr, flags=re.S)
# ports inside `ifdef blocks (only the lockstep regfile interface, which our config disables)
hdr = re.sub(r"`ifdef\s+\w+.*?`endif", "", hdr, flags=re.S)
ports = []  # (dir, width_expr, name); any number of packed dimensions
for m in re.finditer(r"\b(input|output)\s+(?:logic|wire)?\s*((?:\[[^\]]*\]\s*)*)(\w+)", hdr):
    ports.append((m.group(1), m.group(2) or "", m.group(3)))

conns = []
for d, w, n in ports:
    if n in CONNECT:
        conns.append(f"    .{n:<28}({CONNECT[n]})")
    elif d == "input":
        conns.append(f"    .{n:<28}('0)")
    else:
        conns.append(f"    .{n:<28}()")

print(f"""// GENERATED by cores/veer_el2/wrapper/gen_veer_wrap.py from el2_veer.sv. Do not edit.
// VeeR EL2 in the common wrapper interface (common/wrapper/README.md): el2_veer IFU and LSU AXI4
// (64-bit) -> axi2obi64 -> I and D ports. DMA slave, debug system bus, trace, MPC/halt controls and
// the (disabled) DCCM/ICCM/I-cache SRAM ports are tied off. Configuration comes from el2_param.vh
// (cores/veer_el2/config/<cfg>, made by gen_config.sh).
module veer_el2_wrap
import el2_pkg::*;
#(
`include "el2_param.vh"
) (
  input  logic        clk,
  input  logic        rst_n,
  output logic        i_req,
  input  logic        i_gnt,
  output logic [31:0] i_addr,
  input  logic        i_rvalid,
  input  logic [63:0] i_rdata,
  input  logic        i_err,
  output logic        d_req,
  input  logic        d_gnt,
  output logic [31:0] d_addr,
  output logic        d_we,
  output logic [7:0]  d_be,
  output logic [63:0] d_wdata,
  input  logic        d_rvalid,
  input  logic [63:0] d_rdata,
  input  logic        d_err,
  input  logic        irq_timer,
  input  logic        irq_soft,
  input  logic        irq_ext
);
  // AXI signals between the core and the adapters""")
for ch, tag in (("lsu", "pt.LSU_BUS_TAG"), ("ifu", "pt.IFU_BUS_TAG")):
    print(f"""  logic                {ch}_axi_awvalid, {ch}_axi_awready, {ch}_axi_wvalid, {ch}_axi_wready, {ch}_axi_wlast;
  logic                {ch}_axi_bvalid, {ch}_axi_bready, {ch}_axi_arvalid, {ch}_axi_arready;
  logic                {ch}_axi_rvalid, {ch}_axi_rready, {ch}_axi_rlast;
  logic [{tag}-1:0] {ch}_axi_awid, {ch}_axi_bid, {ch}_axi_arid, {ch}_axi_rid;
  logic [31:0]         {ch}_axi_awaddr, {ch}_axi_araddr;
  logic [7:0]          {ch}_axi_awlen, {ch}_axi_arlen, {ch}_axi_wstrb;
  logic [63:0]         {ch}_axi_wdata, {ch}_axi_rdata;
  logic [1:0]          {ch}_axi_bresp, {ch}_axi_rresp;""")
print("""
  el2_veer #(.pt(pt)) u_core (""")
print(",\n".join(conns))
print("""  );

  logic [7:0]  i_be_unused;
  logic [63:0] i_wdata_unused;
  logic        i_we_unused;

  // IFU: read-only AXI port
  axi2obi64 #(.ID_W(pt.IFU_BUS_TAG)) u_ifu (
    .clk, .rst_n,
    .awvalid (ifu_axi_awvalid), .awready (ifu_axi_awready), .awid (ifu_axi_awid), .awaddr (ifu_axi_awaddr),
    .awlen (ifu_axi_awlen), .wvalid (ifu_axi_wvalid), .wready (ifu_axi_wready), .wdata (ifu_axi_wdata),
    .wstrb (ifu_axi_wstrb), .wlast (ifu_axi_wlast), .bvalid (ifu_axi_bvalid), .bready (ifu_axi_bready),
    .bid (ifu_axi_bid), .bresp (ifu_axi_bresp),
    .arvalid (ifu_axi_arvalid), .arready (ifu_axi_arready), .arid (ifu_axi_arid), .araddr (ifu_axi_araddr),
    .arlen (ifu_axi_arlen), .rvalid (ifu_axi_rvalid), .rready (ifu_axi_rready), .rid (ifu_axi_rid),
    .rdata (ifu_axi_rdata), .rresp (ifu_axi_rresp), .rlast (ifu_axi_rlast),
    .req (i_req), .gnt (i_gnt), .addr (i_addr), .we (i_we_unused), .be (i_be_unused), .wdata_o (i_wdata_unused),
    .m_rvalid (i_rvalid), .m_rdata (i_rdata), .m_err (i_err)
  );

  // LSU
  axi2obi64 #(.ID_W(pt.LSU_BUS_TAG)) u_lsu (
    .clk, .rst_n,
    .awvalid (lsu_axi_awvalid), .awready (lsu_axi_awready), .awid (lsu_axi_awid), .awaddr (lsu_axi_awaddr),
    .awlen (lsu_axi_awlen), .wvalid (lsu_axi_wvalid), .wready (lsu_axi_wready), .wdata (lsu_axi_wdata),
    .wstrb (lsu_axi_wstrb), .wlast (lsu_axi_wlast), .bvalid (lsu_axi_bvalid), .bready (lsu_axi_bready),
    .bid (lsu_axi_bid), .bresp (lsu_axi_bresp),
    .arvalid (lsu_axi_arvalid), .arready (lsu_axi_arready), .arid (lsu_axi_arid), .araddr (lsu_axi_araddr),
    .arlen (lsu_axi_arlen), .rvalid (lsu_axi_rvalid), .rready (lsu_axi_rready), .rid (lsu_axi_rid),
    .rdata (lsu_axi_rdata), .rresp (lsu_axi_rresp), .rlast (lsu_axi_rlast),
    .req (d_req), .gnt (d_gnt), .addr (d_addr), .we (d_we), .be (d_be), .wdata_o (d_wdata),
    .m_rvalid (d_rvalid), .m_rdata (d_rdata), .m_err (d_err)
  );
endmodule""")
